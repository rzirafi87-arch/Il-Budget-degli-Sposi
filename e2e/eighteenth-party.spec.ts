import {partyText} from "../src/features/events/eighteenth/copy";
import { test, expect } from "@playwright/test";
import { createClient } from "@supabase/supabase-js";
import {blankPlan} from "../src/features/events/baptism/model";
import { randomUUID } from "node:crypto";
import { createQaIdentity, login } from "./helpers/milestone8-fixtures";

test("[18] party setup, expense, RSVP, sign-in and event isolation", async ({ page }) => {
  const url = process.env.PLAYWRIGHT_SUPABASE_URL!;
  expect(["127.0.0.1", "localhost"]).toContain(new URL(url).hostname);
  const user = await createQaIdentity("party18");
  // The workflow destroys this isolated database and its identities after the test.
  {
    await login(page, user);
    await page.goto("/it/select-country");
    await page.getByRole("button", {name:"Italia", exact:true}).click();
    await page.getByRole("button", {name:/^avanti$/i}).click();
    await page.getByRole("button", {name:/18|diciott/i}).first().click();
    await page.getByLabel("Nome di chi compie 18 anni").fill("Sofia QA");
    await page.getByLabel("Data della festa").fill("2027-05-01");
    await page.getByLabel("Budget iniziale").fill("1500");
    await page.getByRole("button", {name:"Organizza la festa"}).click();
    await expect(page.getByRole("heading", {name:"Sofia QA"})).toBeVisible();
    await page.getByRole("combobox", {name:"Chi organizza?",exact:true}).selectOption("organizer");
    await page.getByLabel("Nome di chi festeggia", {exact:true}).fill("Sofia");
    await page.getByLabel("Luogo della festa", {exact:true}).fill("Sala QA");
    await page.getByLabel("Indirizzo", {exact:true}).fill("Via QA 18");
    await page.getByLabel("Ora di inizio", {exact:true}).fill("19:00");
    await page.getByLabel("Note private (escluse dall’invito)", {exact:true}).fill("PRIVATE-PARTY-NOTE");
    await page.getByRole("button", {name:"Programma",exact:true}).click();
    await page.getByRole("button", {name:"Aggiungi attività",exact:true}).click();
    await page.getByLabel("Attività", {exact:true}).fill("Taglio torta");
    await page.getByLabel("Data e ora", {exact:true}).fill("2027-05-02T00:15");
    await page.getByRole("button", {name:"Invito",exact:true}).click();
    await page.getByLabel("Risposta entro", {exact:true}).fill("2027-04-25");
    await page.getByLabel("Contatto per le conferme", {exact:true}).fill("Referente QA");
    expect(await page.getByRole("textbox", {name:"Anteprima invito",exact:true}).inputValue()).not.toContain("PRIVATE-PARTY-NOTE");
    await expect(page.getByRole("button", {name:"Copia invito",exact:true})).toBeEnabled();
    await page.getByRole("button", {name:"Salva dettagli festa",exact:true}).click();
    await expect(page.getByRole("status")).toHaveText("Dettagli salvati.");
    await page.getByRole("button",{name:"Checklist",exact:true}).click();
    await page.getByRole("checkbox",{name:/Definisci il budget/}).check();
    await page.getByRole("button",{name:"Salva dettagli festa",exact:true}).click();
    await expect(page.getByRole("status")).toHaveText("Dettagli salvati.");
    await page.goto("/it/timeline");
    await expect(page.getByRole("heading",{name:"Timeline della festa",exact:true})).toBeVisible();
    await expect(page.getByRole("checkbox",{name:/Definisci il budget/})).toBeChecked();
    await expect(page.locator('time[datetime="2027-03-02"]')).toBeVisible();
    await page.getByRole("checkbox",{name:/Conferma il luogo della festa/}).check();
    await page.getByRole("button",{name:"Salva dettagli festa",exact:true}).click();
    await expect(page.getByRole("status")).toHaveText("Dettagli salvati.");
    await page.getByRole("link",{name:"Torna alla festa",exact:true}).click();
    await page.getByRole("button",{name:"Checklist",exact:true}).click();
    await expect(page.getByRole("checkbox",{name:/Conferma il luogo della festa/})).toBeChecked();
    await page.getByLabel("Categoria").selectOption("cake");
    await page.getByLabel("Importo").fill("120");
    await page.getByRole("button", {name:"Registra spesa"}).click();
    const balance = page.getByText("Disponibilità dopo le spese pagate").locator("..");
    await expect(balance).toContainText("1.380");
    await page.getByLabel("Importo",{exact:true}).fill("200");
    await page.getByRole("button",{name:"Salva preventivo",exact:true}).click();
    await page.getByRole("button",{name:"Registra acconto o saldo",exact:true}).click();
    await page.getByLabel("Importo pagamento (€)",{exact:true}).fill("20");
    await page.getByLabel("Data pagamento",{exact:true}).fill("2027-01-10");
    await page.getByRole("button",{name:"Conferma pagamento",exact:true}).click();
    await expect(balance).toContainText("1.360");
    const auth = createClient(url, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!);
    const session = await auth.auth.signInWithPassword(user);
    const headers = { Authorization: "Bearer " + session.data.session!.access_token };
    const guests = { familyGroups: [], nonInvitedRecipients: [], guests: [{ id:randomUUID(), name:"Alex QA", guestType:"common", attending:true, rsvpReceived:true }] };
    expect((await page.request.post("/api/my/guests", {headers, data:guests})).ok()).toBe(true);
    await page.goto("/it/profilo");
    await page.getByRole("button", {name:/esci/i}).click();
    await page.waitForURL(/\/it\/?$/);
    await login(page, user);
    await page.goto("/it/dashboard");
    await page.reload();
    await expect(balance).toContainText("1.360");
    const snapshot = await page.request.get("/api/my/guests", {headers});
    expect((await snapshot.json()).guests).toEqual([expect.objectContaining({name:"Alex QA", attending:true, rsvpReceived:true})]);
    for (const locale of ["it","en","es","fr","de"]) {
      await page.goto("/" + locale + "/dashboard");
      await expect(page.getByRole("heading", {name:"Sofia QA"})).toBeVisible();
      await expect(page.getByRole("heading",{name:partyText(locale,"La tua festa, passo dopo passo"),exact:true})).toBeVisible();
      await page.getByRole("button",{name:partyText(locale,"Checklist"),exact:true}).click();
      await expect(page.getByRole("checkbox",{name:new RegExp(partyText(locale,"Definisci il budget"))})).toBeChecked();
      await expect(page.getByRole("checkbox",{name:new RegExp(partyText(locale,"Conferma il luogo della festa"))})).toBeChecked();
      await page.getByRole("button",{name:partyText(locale,"Invito"),exact:true}).click();
      const translatedInvite=await page.getByRole("textbox",{name:partyText(locale,"Anteprima invito"),exact:true}).inputValue();
      expect(translatedInvite).not.toContain("PRIVATE-PARTY-NOTE");
      if(locale!=="it")expect(translatedInvite).not.toContain("Festeggiamo insieme");
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    }
    const wedding = await page.request.post("/api/event/ensure-default", {headers, data:{eventType:"wedding", country:"it", language:"it", createAdditional:true}});
    expect(wedding.ok()).toBe(true);
    const {eventId} = await wedding.json();
    // Chromium owns the active-event cookie used by the real dashboard.
    await page.evaluate(async ({headers, eventId}) => {
      const selected = await fetch("/api/my/current-event", {method:"POST",
        headers:{...headers,"Content-Type":"application/json"}, body:JSON.stringify({eventId})});
      if (!selected.ok) throw new Error("Event selection failed: " + selected.status);
    }, {headers, eventId});
    const otherGuests = await page.evaluate(async headers => {
      const r = await fetch("/api/my/guests", {headers});
      if (!r.ok) throw new Error("Guest read failed: " + r.status);
      return (await r.json()).guests;
    }, headers);
    expect(otherGuests).toHaveLength(0);
    expect(await page.evaluate(async headers => (await fetch("/api/my/eighteenth-dashboard", {headers})).status, headers)).toBe(409);
    await page.goto("/it/dashboard");
    await expect(page.getByRole("progressbar")).toBeVisible();
    await page.getByRole("button", { name: /^apri impostazioni$/i }).click();
    const settings = page.getByRole("dialog", { name: "Impostazioni", exact: true });
    await expect(settings.getByRole("link", { name: "Aggiungi un evento" })).toHaveAttribute("href", "/it/select-event-type?new=1");
    const selector = settings.getByRole("combobox", { name: /Cambia evento/i });
    const partyId = await selector.getByRole("option", { name: /Sofia QA/ }).getAttribute("value");
    expect(partyId).toBeTruthy();
    const savedPlan=await auth.from("eighteenth_party_plans").select("plan").eq("event_id",partyId!).single();
    expect(savedPlan.error).toBeNull();
    expect(savedPlan.data?.plan).toMatchObject({role:"organizer",celebrant:"Sofia",programme:[expect.objectContaining({title:"Taglio torta",at:"2027-05-02T00:15"})]});
    await selector.selectOption(partyId!);
    await settings.getByRole("button", { name: "Cambia evento", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Sofia QA" })).toBeVisible();
    await expect(balance).toContainText("1.360");
    const baptismId=randomUUID();
    const baptism=await auth.rpc("save_family_baptism",{p_id:baptismId,p_revision:0,p_plan:{...blankPlan(),name:"QA-M8-BATTESIMO-ISOLATO",draft:false,ceremony:"2030-05-18T10:30",ceremonyConfirmed:true,community:"Comunità QA",venue:"Chiesa QA",address:"Via QA",scenario:"solo",budget:"500",replyBy:"2030-05-08",replyContact:"Referente QA"}});
    expect(baptism.error).toBeNull();
    async function selectEvent(id:string){await page.evaluate(async({headers,id})=>{const r=await fetch("/api/my/current-event",{method:"POST",headers:{...headers,"Content-Type":"application/json"},body:JSON.stringify({eventId:id})});if(!r.ok)throw new Error("Selection failed "+r.status);},{headers,id});}
    await selectEvent(baptismId);
    await page.goto("/it/battesimo?eventId="+baptismId);
    await expect(page.getByRole("heading",{name:"Il battesimo di QA-M8-BATTESIMO-ISOLATO",exact:true})).toBeVisible();
    expect(await page.evaluate(async headers=>(await fetch("/api/my/eighteenth-dashboard",{headers})).status,headers)).toBe(409);
    const baptismSnapshot=await auth.rpc("read_family_baptism",{p_id:baptismId});
    expect(baptismSnapshot.data.plan.guests).toHaveLength(0);
    expect(baptismSnapshot.data.plan.costs).toHaveLength(0);
    await selectEvent(partyId!);await page.goto("/it/dashboard");
    await expect(page.getByRole("heading",{name:"Sofia QA",exact:true})).toBeVisible();
    await expect(balance).toContainText("1.360");
    const partyExpenses=await page.evaluate(async headers=>{const r=await fetch("/api/my/eighteenth-dashboard",{headers});const body=await r.json();if(!r.ok)throw new Error(JSON.stringify(body));return body;},headers);
    expect(partyExpenses.entries.reduce((sum:number,e:{paid:number})=>sum+e.paid,0)).toBe(140);
  }
});
